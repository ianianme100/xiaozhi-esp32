SensorDisplay::SensorDisplay(i2c_master_bus_handle_t bus, uint8_t i2c_addr) {
    i2c_device_config_t cfg = {
        .dev_addr_length = I2C_ADDR_BIT_LEN_7,
        .device_address = i2c_addr,
        .scl_speed_hz = 400 * 1000,
        .scl_wait_us = 0,
        .flags = { .disable_ack_check = 0 },
    };
    ESP_ERROR_CHECK(i2c_master_bus_add_device(bus, &cfg, &dev_));
    Initialize();
}

void SensorDisplay::SendCommands(const uint8_t* cmds, size_t len) {
    i2c_master_transmit(dev_, cmds, len, 200);
}

void SensorDisplay::Initialize() {
    SendCommands(ssd1306_init_cmds, sizeof(ssd1306_init_cmds));
    Clear();
    Flush();
}

void SensorDisplay::Clear() {
    memset(pages_, 0, sizeof(pages_));
}

// col: pixel column 0–127, page: row page 0–7 (each page = 8 pixels tall)
void SensorDisplay::PutChar(int col, int page, char c) {
    if (c < 0x20 || c > 0x7E) c = ' ';
    const uint8_t* glyph = font8[c - 0x20];
    for (int row = 0; row < 8; row++) {
        uint8_t bits = glyph[row];  // bit7=leftmost pixel
        for (int bit = 0; bit < 8; bit++) {
            int px = col + bit;
            if (px >= 128) break;
            // In page mode: each byte in pages_[page][col] has bit0=top row of page
            // We are filling one full page per character row
            if (bits & (0x80 >> bit)) {
                pages_[page][px] |= (1 << row);
            }
        }
    }
}

void SensorDisplay::PutStr(int col, int page, const char* str) {
    while (*str && col < 128) {
        PutChar(col, page, *str++);
        col += 8;
    }
}

void SensorDisplay::Flush() {
    for (int p = 0; p < 8; p++) {
        // Set page, column start
        uint8_t cmds[4] = {0x00, (uint8_t)(0xB0 | p), 0x00, 0x10};
        SendCommands(cmds, sizeof(cmds));

        // Send 128 bytes of pixel data for this page
        uint8_t data[129];
        data[0] = 0x40;  // data control byte
        memcpy(&data[1], pages_[p], 128);
        i2c_master_transmit(dev_, data, sizeof(data), 200);
    }
}

void SensorDisplay::ShowAirQuality(int32_t tvoc_ppb) {
    Clear();

    // Row 0 (page 0): header
    PutStr(0, 0, "  Air Quality   ");

    // Row 1 (page 1): separator
    PutStr(0, 1, "----------------");

    if (tvoc_ppb < 0) {
        PutStr(0, 3, "  Warming up... ");
    } else {
        char line[17];

        // Row 2 (page 2): TVOC value
        snprintf(line, sizeof(line), "TVOC:%5ld ppb  ", (long)tvoc_ppb);
        PutStr(0, 2, line);

        // Row 3 (page 3): level
        const char* level;
        if      (tvoc_ppb < 220)  level = "Level:    Good  ";
        else if (tvoc_ppb < 660)  level = "Level:    Fair  ";
        else if (tvoc_ppb < 2200) level = "Level:    Poor  ";
        else                      level = "Level: VeryPoor ";
        PutStr(0, 3, level);
    }

    // Row 7 (page 7): separator
    PutStr(0, 7, "----------------");

    Flush();
}
